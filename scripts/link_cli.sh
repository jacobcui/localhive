#!/usr/bin/env bash
# Install a 'localhive' command into ~/.local/bin so it can be run from
# anywhere, not just from inside the repo.
#
# Creates a tiny shim that forwards to this checkout's virtualenv, so the
# venv stays self-contained and nothing is installed system-wide.
set -euo pipefail

say()  { printf '\033[36m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[33mwarning:\033[0m %s\n' "$*" >&2; }

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VENV_BIN="$REPO_DIR/.venv/bin/localhive"
BIN_DIR="${LOCALHIVE_BIN_DIR:-$HOME/.local/bin}"
SHIM="$BIN_DIR/localhive"

if [ ! -x "$VENV_BIN" ]; then
  warn "$VENV_BIN not found - run 'make deps' first"
  exit 1
fi

mkdir -p "$BIN_DIR"

# Refuse to clobber something that is not one of our shims.
if [ -e "$SHIM" ] && ! grep -q "localhive shim" "$SHIM" 2>/dev/null; then
  warn "$SHIM already exists and is not a localhive shim; leaving it alone"
  warn "run it directly instead: $VENV_BIN"
  exit 1
fi

cat > "$SHIM" <<EOF
#!/usr/bin/env bash
# localhive shim - forwards to the checkout at $REPO_DIR
# Generated by 'make link'. Safe to delete.
exec "$VENV_BIN" "\$@"
EOF
chmod +x "$SHIM"

say "installed $SHIM"
say "  -> $VENV_BIN"

# Make sure ~/.local/bin is on PATH for future shells.
case ":$PATH:" in
  *":$BIN_DIR:"*) ;;
  *)
    warn "$BIN_DIR is not on your PATH"
    warn "add this to your shell rc:  export PATH=\"$BIN_DIR:\$PATH\""
    ;;
esac

if command -v localhive >/dev/null 2>&1; then
  say "ready: $(command -v localhive)"
else
  warn "open a new shell, then 'localhive --help' will work"
fi
